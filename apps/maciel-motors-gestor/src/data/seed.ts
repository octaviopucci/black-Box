function daysAgo(n: number): string {
  const d = new Date()
  d.setDate(d.getDate() - n)
  return d.toISOString().slice(0, 10)
}

function isoDaysAgo(n: number): string {
  const d = new Date()
  d.setDate(d.getDate() - n)
  return d.toISOString()
}

function expense(
  id: string,
  vehicleId: string,
  descricao: string,
  categoria: Expense['categoria'],
  valor: number,
  days: number,
  observacao = '',
): Expense {
  return {
    id,
    vehicleId,
    descricao,
    categoria,
    valor,
    data: daysAgo(days),
    observacao,
    createdAt: isoDaysAgo(days),
    updatedAt: isoDaysAgo(days),
  }
}

function makeSale(
  id: string,
  vehicle: Vehicle,
  expenses: Expense[],
  customer: Customer,
  opts: {
    daysAgoSale: number
    valorVendido: number
    comissao: number
    formaPagamento: Sale['formaPagamento']
    entrada: number
    parcelas: number
    observacoes?: string
  },
): Sale {
  const dataVenda = daysAgo(opts.daysAgoSale)
  const metrics = calcSaleMetrics(
    vehicle,
    expenses,
    opts.valorVendido,
    opts.comissao,
    dataVenda,
  )
  return {
    id,
    vehicleId: vehicle.id,
    customerId: customer.id,
    clienteNome: customer.nome,
    cpf: customer.cpf,
    telefone: customer.telefone,
    cidade: customer.cidade,
    endereco: customer.endereco,
    dataVenda,
    formaPagamento: opts.formaPagamento,
    entrada: opts.entrada,
    parcelas: opts.parcelas,
    valorVendido: opts.valorVendido,
    comissao: opts.comissao,
    observacoes: opts.observacoes || '',
    lucroBruto: metrics.lucroBruto,
    lucroLiquido: metrics.lucroLiquido,
    roi: metrics.roi,
    margem: metrics.margem,
    diasEstoque: metrics.diasEstoque,
    createdAt: isoDaysAgo(opts.daysAgoSale),
    updatedAt: isoDaysAgo(opts.daysAgoSale),
  }
}

